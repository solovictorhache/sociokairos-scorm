const SK_LANG_LOCALE = { es: "es-ES", en: "en-US", pt: "pt-BR" };

let SK_LANG = "es";

function skT(key) {
  const dict = SK_I18N[SK_LANG] || SK_I18N.es;
  return dict[key] != null ? dict[key] : (SK_I18N.es[key] != null ? SK_I18N.es[key] : key);
}

function skLocale() {
  return SK_LANG_LOCALE[SK_LANG] || "es-ES";
}

function skAplicarIdioma(lang) {
  if (!SK_I18N[lang]) lang = "es";
  SK_LANG = lang;
  try { localStorage.setItem("sk_lang", lang); } catch (e) { /* localStorage no disponible */ }

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = skT(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", skT(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", skT(el.getAttribute("data-i18n-title")));
  });

  document.querySelectorAll(".sk-lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });

  // Los bloques que mezclan texto de plantilla con contenido ya generado
  // por el motor (en español, por diseño — ver la nota al principio de
  // este archivo) se vuelven a pintar para que al menos su parte de
  // plantilla cambie de idioma sin duplicar el análisis.
  if (typeof skOnIdiomaCambiado === "function") skOnIdiomaCambiado();
}

function skSetIdioma(lang) {
  skAplicarIdioma(lang);
}

function skInitIdioma() {
  let guardado = "es";
  try { guardado = localStorage.getItem("sk_lang") || "es"; } catch (e) { /* no disponible */ }
  skAplicarIdioma(SK_I18N[guardado] ? guardado : "es");
}
